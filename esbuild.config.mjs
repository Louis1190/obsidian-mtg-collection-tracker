import esbuild from "esbuild";
import process from "process";
import fs from "node:fs";
import path from "node:path";
import { builtinModules } from "node:module";
import { embedPlugin } from "./esbuild-embed.mjs";

// MTG_SWAP="from=to[,from=to]" (paths relative to the folder the build runs in): wherever the bundle would read `from`, it reads `to` instead. Unset, this plugin does
// nothing and the output is exactly what it was without it. Only the publication rehearsal sets it, to build this tree with the stand-in of a part the public copy leaves out.
const swaps = (process.env.MTG_SWAP ?? "")
	.split(",")
	.filter(Boolean)
	.map((pair) => pair.split("=").map((p) => path.resolve(p)));
const swapPlugin = {
	name: "swap",
	setup(build) {
		if (swaps.length === 0) return;
		build.onLoad({ filter: /\.ts$/ }, async (args) => {
			const hit = swaps.find(([from]) => from === args.path);
			if (!hit) return undefined;
			return { contents: await fs.promises.readFile(hit[1], "utf8"), loader: "ts", resolveDir: path.dirname(args.path) };
		});
	},
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	plugins: [embedPlugin, swapPlugin],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
